export function getCardForChapter(chapter: number, cardIndex: number): CardData | undefined {
  return cards.find((c) => c.chapter === chapter && c.cardIndex === cardIndex);
}

export function getCardsForChapter(chapter: number): CardData[] {
  return cards.filter((c) => c.chapter === chapter).sort((a, b) => a.cardIndex - b.cardIndex);
}
